"""Verdict invariants (release gate, layer 3): what must always be true of a verdict, then attacked.

- Must-fail matrix: for every check type, fake driver observations where the check must fail. Each
  check goes through the real validator and the real scheduler (positive checks through run_check,
  post-convergence checks through converge_then_hold), and the result must be `failed`, never `passed`.
- Metamorphic tests: a lab state that passes a whole spec flips to failed when one route leaks, one
  session goes down, or a neighbor sends prefixes over a bound. The base state and the mutation are
  generated by Hypothesis.

No lab and no containers: the driver is a static snapshot of device state and the clock is fake.
"""
from __future__ import annotations

import copy
from dataclasses import dataclass, field

import pytest
from hypothesis import HealthCheck, given, settings
from hypothesis import strategies as st
from test_checks import FakeClock

from netdryrun.checks import converge_then_hold, hold_together, is_post_convergence, run_check, run_round_robin
from netdryrun.config import _validate_check
from netdryrun.drivers.base import BgpNeighbor, BgpPath, Observation, Route


@dataclass
class State:
    """A snapshot of one node's state, as the drivers normalize it."""
    neighbors: dict[str, BgpNeighbor] = field(default_factory=dict)
    routes: dict[str, list[Route]] = field(default_factory=dict)        # prefix -> routes
    paths: dict[str, list[BgpPath]] = field(default_factory=dict)       # prefix -> BGP paths
    pings: dict[str, tuple[int, int]] = field(default_factory=dict)     # target -> (sent, received)


class StateDriver:
    def __init__(self, state: State):
        self.state = state

    def bgp_neighbors(self, vrf="default"):
        return Observation(dict(self.state.neighbors), [])

    def routes(self, prefix, vrf="default"):
        return Observation(list(self.state.routes.get(prefix, [])), [])

    def bgp_paths(self, prefix, vrf="default"):
        return Observation(list(self.state.paths.get(prefix, [])), [])

    def ping(self, target, source, count, vrf="default"):
        sent, received = self.state.pings.get(target, (count, count))
        return Observation((sent, received), [{"stderr": "" if sent else "ping: bind: Cannot assign requested address"}])


def make(raw: dict, timeout: float = 20):
    """A check through the real validator, so the matrix tests what a user's YAML turns into."""
    return _validate_check(0, dict(raw), timeout)


def verdict(check, state: State) -> bool:
    clock = FakeClock()
    driver = StateDriver(state)
    if is_post_convergence(check):
        r = converge_then_hold(check, driver, hold=10, interval=3, clock=clock, sleep=clock.sleep)
    else:
        r = run_check(check, driver, interval=3, clock=clock, sleep=clock.sleep)
    return r.passed


N = "10.0.0.2"
P = "10.66.0.0/16"


def nb(state="established", v4=5, **families):
    prefixes = {"ipv4-unicast": v4, **{k.replace("_", "-"): v for k, v in families.items()}}
    return {N: BgpNeighbor(N, state, prefixes)}


def path(best=True, as_path="65002", next_hop="10.0.0.2", local_pref=100, med=0, communities=(), **kw):
    return BgpPath(best, as_path, next_hop, local_pref, med, list(communities), **kw)


def rt(proto="bgp", active=True):
    return [Route(P, proto, active)]


