@pytest.mark.parametrize("raw,state", [pytest.param(raw, state, id=label) for label, raw, state in MUST_FAIL])
def test_must_fail(raw, state):
    assert verdict(make(raw), state) is False


def _check_types():
    from netdryrun.checks import EVALUATORS
    from netdryrun.config import CHECK_TYPES
    return sorted(set(CHECK_TYPES) | set(EVALUATORS))


@pytest.mark.parametrize("ctype", _check_types())
def test_meta_every_check_type_has_must_fail_cases(ctype):
    """Meta-test: the safety tests can't be skipped. A new check type (in config.CHECK_TYPES or the
    evaluator registry) without must-fail cases here turns CI red, naming the type."""
    cases = [label for label, raw, _ in MUST_FAIL if raw["type"] == ctype]
    assert len(cases) >= 2, f"check type {ctype!r} has no must-fail cases in tests/test_invariants.py MUST_FAIL"


@pytest.mark.parametrize("ctype", _check_types())
def test_meta_every_check_type_is_attacked_by_the_config_properties(ctype):
    """Meta-test: every check type is in the property-based config attack (BASE config) and every one of
    its keys has bad values to attack it with."""
    from netdryrun.config import CHECK_TYPES
    from test_config_properties import BAD, BASE

    assert ctype in CHECK_TYPES, f"check type {ctype!r} has an evaluator but no config schema in CHECK_TYPES"
    in_base = [c for c in BASE["checks"] + [c for sc in BASE["scenarios"] for c in sc["checks"]] if c["type"] == ctype]
    assert in_base, f"check type {ctype!r} is missing from BASE in tests/test_config_properties.py"
    spec = CHECK_TYPES[ctype]
    keys = set(spec["required"]) | set(spec["optional"])
    missing = sorted(keys - set(BAD))
    assert not missing, f"check type {ctype!r}: keys {missing} have no bad values in tests/test_config_properties.py BAD"
    unused = sorted(keys - {k for c in in_base for k in c})
    assert not unused, f"check type {ctype!r}: keys {unused} never appear in BASE, so no property test attacks them"


