# --- metamorphic: a passing state plus one fault flips to failed ------------------------------------------

NODES = ("r1", "r2", "r3")
NEIGHBOR = {"r1": "10.0.12.2", "r2": "10.0.12.1", "r3": "10.0.23.2"}
OWN = {"r1": "192.168.1.0/24", "r2": "192.168.2.0/24", "r3": "192.168.3.0/24"}
LEAK = "203.0.113.0/24"


def base_states(counts: dict[str, int]) -> dict[str, State]:
    """Three healthy routers: sessions up, every router has the others' routes, no leak, pings work."""
    out = {}
    for n in NODES:
        s = State(neighbors={NEIGHBOR[n]: BgpNeighbor(NEIGHBOR[n], "established", {"ipv4-unicast": counts[n]})})
        for m in NODES:
            proto = "connected" if m == n else "bgp"
            s.routes[OWN[m]] = [Route(OWN[m], proto, True)]
            s.paths[OWN[m]] = [path(as_path="" if m == n else "65002")]
        out[n] = s
    return out


def spec(bounds: dict[str, int]) -> list:
    checks = []
    for n in NODES:
        checks.append(make({"type": "bgp_session", "node": n, "neighbor": NEIGHBOR[n]}))
        checks.append(make({"type": "bgp_prefixes", "node": n, "neighbor": NEIGHBOR[n], "min": 1, "max": bounds[n]}))
        checks.append(make({"type": "route", "node": n, "prefix": LEAK, "present": False}))
        checks.append(make({"type": "route", "node": n, "prefix": LEAK, "protocol": "bgp", "present": False}))
        checks.append(make({"type": "bgp_route", "node": n, "prefix": LEAK, "present": False}))
        for m in NODES:
            if m != n:
                checks.append(make({"type": "route", "node": n, "prefix": OWN[m], "protocol": "bgp"}))
        checks.append(make({"type": "ping", "node": n, "target": "192.168.9.1", "expect": "failure"}))
    return checks


def run_spec(checks, states) -> list:
    """The runner's own scheduling: positives round-robin, then post-convergence checks held together."""
    clock = FakeClock()
    drivers = {n: StateDriver(s) for n, s in states.items()}
    pos = [c for c in checks if not is_post_convergence(c)]
    neg = [c for c in checks if is_post_convergence(c)]
    results = run_round_robin(pos, drivers, clock=clock, sleep=clock.sleep)
    results += hold_together(neg, drivers, hold=10, clock=clock, sleep=clock.sleep)
    return results


def unreachable(states):
    for s in states.values():
        s.pings["192.168.9.1"] = (3, 0)


def leak_route(states, node, selected):
    states[node].routes[LEAK] = [Route(LEAK, "bgp", selected)]


def leak_bgp_only(states, node):
    # in the BGP table but not the routing table (lost to a local route on SR Linux / EOS)
    states[node].paths[LEAK] = [path(best=False)]


def session_down(states, node, new_state):
    nbr = states[node].neighbors[NEIGHBOR[node]]
    states[node].neighbors[NEIGHBOR[node]] = BgpNeighbor(nbr.address, new_state, dict(nbr.prefixes))


def over_bound(states, node, bounds, extra):
    nbr = states[node].neighbors[NEIGHBOR[node]]
    nbr.prefixes["ipv4-unicast"] = bounds[node] + extra


def lose_route(states, node):
    other = next(m for m in NODES if m != node)
    states[node].routes.pop(OWN[other])


def reachable(states, node):
    states[node].pings["192.168.9.1"] = (3, 3)


mutations = st.one_of(
    st.tuples(st.just("leak_route"), st.sampled_from(NODES), st.booleans()),
    st.tuples(st.just("leak_bgp_only"), st.sampled_from(NODES)),
    st.tuples(st.just("session_down"), st.sampled_from(NODES),
              st.sampled_from(["idle", "active", "connect", "opensent", "openconfirm"])),
    st.tuples(st.just("over_bound"), st.sampled_from(NODES), st.integers(1, 5000)),
    st.tuples(st.just("lose_route"), st.sampled_from(NODES)),
    st.tuples(st.just("reachable"), st.sampled_from(NODES)),
)


@settings(max_examples=150, deadline=None, suppress_health_check=[HealthCheck.too_slow])
@given(bounds=st.fixed_dictionaries({n: st.integers(1, 100) for n in NODES}), data=st.data(), mutation=mutations)
def test_metamorphic_one_fault_flips_a_passing_state(bounds, data, mutation):
    counts = {n: data.draw(st.integers(1, bounds[n]), label=f"count {n}") for n in NODES}
    checks = spec(bounds)
    states = base_states(counts)
    unreachable(states)
    good = run_spec(checks, states)
    assert all(r.passed for r in good), [r.detail for r in good if not r.passed]

    bad = copy.deepcopy(states)
    kind, node, *args = mutation
    {"leak_route": lambda: leak_route(bad, node, *args),
     "leak_bgp_only": lambda: leak_bgp_only(bad, node),
     "session_down": lambda: session_down(bad, node, *args),
     "over_bound": lambda: over_bound(bad, node, bounds, *args),
     "lose_route": lambda: lose_route(bad, node),
     "reachable": lambda: reachable(bad, node)}[kind]()
    results = run_spec(checks, bad)
    failed = [r for r in results if not r.passed]
    assert failed, f"{mutation} left every check passing"
    # the failure is on the node that was broken, not an accident elsewhere
    assert any(r.check.node == node for r in failed)


@settings(max_examples=60, deadline=None)
@given(n_extra=st.integers(1, 10_000), bound=st.integers(0, 1000),
       afi=st.sampled_from(["ipv4-unicast", "ipv6-unicast", "evpn"]), form=st.sampled_from(["max", "exact"]))
def test_metamorphic_prefixes_over_any_bound_fail(n_extra, bound, afi, form):
    c = make({**PX, form: bound, "afi": afi})
    ok_state = State(neighbors={N: BgpNeighbor(N, "established", {afi: bound})})
    bad_state = State(neighbors={N: BgpNeighbor(N, "established", {afi: bound + n_extra})})
    assert verdict(c, ok_state) is True
    assert verdict(c, bad_state) is False


@settings(max_examples=60, deadline=None)
@given(late=st.integers(0, 3), selected=st.booleans())
def test_a_leak_that_appears_during_the_hold_fails(late, selected):
    """Post-convergence checks must fail on the first violation inside the hold window, however late."""
    c = make({**R, "present": False})
    clean = []
    leaked = [Route(P, "bgp", selected)]

    class Late(StateDriver):
        calls = 0

        def routes(self, prefix, vrf="default"):
            Late.calls += 1
            return Observation(leaked if Late.calls > late else clean, [])

    clock = FakeClock()
    r = converge_then_hold(c, Late(State()), hold=10, interval=3, clock=clock, sleep=clock.sleep)
    assert r.passed is False
